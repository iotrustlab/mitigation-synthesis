"""One-period view of the reusable bounded-delay proof-template generator.

This module preserves the separately named 1T proof profile, while its
invariants are generated by the same schedule-based machinery used for longer
delays. It is still not a certificate or an authorization decision.
"""

from __future__ import annotations

from .bounded_delay_proof_profile import (
    EXACT_LINEAR_ODE_TACTIC,
    attach_bounded_delay_profile,
    backup_pending_invariant,
    operation_invariant,
    pending_invariant,
)
from .recovery_model_builder import BoundedIsolationSchedule


INTERMEDIATE_DELAY_PROOF_PROFILE_ID = "one-control-period-clock-relative-margins-v1"
INTERMEDIATE_DELAY_SCHEDULE = BoundedIsolationSchedule(0.5, 1, 3)


def attach_intermediate_delay_profile(session) -> list[dict[str, str]]:
    """Attach generated 1T annotations without reusing a 2T proof artifact."""

    return attach_bounded_delay_profile(
        session,
        INTERMEDIATE_DELAY_SCHEDULE,
        profile_id=INTERMEDIATE_DELAY_PROOF_PROFILE_ID,
    )


# Compatibility exports for readers of the previous dedicated profile.
PENDING_INVARIANT = pending_invariant(INTERMEDIATE_DELAY_SCHEDULE, 0)
BACKUP_PENDING_INVARIANT = backup_pending_invariant(INTERMEDIATE_DELAY_SCHEDULE)
OPERATION_INVARIANT = operation_invariant()
